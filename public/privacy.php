            <h2>Children</h2>
            <p>Build a Brainrot is made for children aged 7 and up. We designed it so that children never need to give us any personal information: there is no sign-up, no email, no password and no chat.</p>
            <p>The one place a child can type is the text tool in the scene builder (up to 30 characters each time). That text becomes part of the creation and its share link. We do not check it, and anyone who has the link can see it. Please help your child to keep names, schools, addresses and other personal details out of their creations, and to share links only with people they know.</p>

            <h2>What we collect and why</h2>
            <p><strong>Server logs.</strong> Our web server records each request: IP address, date and time, the page address, the referring page and the browser&rsquo;s user-agent text. When someone opens a share link, the page address contains the creation itself, including any typed text. We use logs only to keep the site running and secure and to fix faults. Lawful basis: legitimate interests (UK GDPR Article 6(1)(f)). The site&rsquo;s code does not set a period for keeping these logs; we do not use them to build profiles and we do not share them.</p>
            <p><strong>Your creation.</strong> While you build, your choices are kept in your own browser (see the table below). When you press finish, the whole creation is packed into the share link. It is not saved in a database on our server. Lawful basis: legitimate interests, to give you the creation and link you asked for.</p>
            <p><strong>Short links (is.gd).</strong> When you finish, the site automatically sends your full share link to <a href="https://is.gd/" rel="noopener noreferrer">is.gd</a>, a free link-shortening service, to get a shorter link. is.gd therefore receives the link (and so the creation, including any typed text) and your IP address, and keeps the short link working under its own terms. If the shortening fails, you get the long link instead.</p>
            <p><strong>Share preview pictures.</strong> When a share link is posted on a social network, our server makes a preview picture. The picture is the same for every creation (&ldquo;Check out my brainrot!&rdquo;) and contains nothing from the creation. It is kept on the server for up to a day before it is made again.</p>
            <p>We do not collect names, email addresses or payment details, we do not sell data, and we do not use data for marketing.</p>

